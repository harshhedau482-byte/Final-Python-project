import pandas as pd
import matplotlib.pyplot as plt

# COVID-19 sample dataset
data = {
    'Date': ['2020-03-01', '2020-04-01', '2020-05-01',
             '2020-06-01', '2020-07-01'],
    'Cases': [100, 500, 1200, 2500, 4000],
    'Recoveries': [20, 200, 700, 1800, 3200],
    'Deaths': [2, 15, 40, 80, 120]
}

# Create DataFrame
df = pd.DataFrame(data)

# Display the dataset
print("COVID-19 Data Analysis")
print(df)

# Plot COVID-19 data
plt.figure(figsize=(10, 5))

plt.plot(df['Date'], df['Cases'], marker='o',
         label='Cases')
plt.plot(df['Date'], df['Recoveries'], marker='o',
         label='Recoveries')
plt.plot(df['Date'], df['Deaths'], marker='o',
         label='Deaths')

plt.title('COVID-19 Data Analysis')
plt.xlabel('Date')
plt.ylabel('Number of People')
plt.legend()
plt.grid(True)

plt.show()

# Display maximum cases
print("\nMaximum Cases:", df['Cases'].max())
print("Maximum Recoveries:", df['Recoveries'].max())
print("Maximum Deaths:", df['Deaths'].max())